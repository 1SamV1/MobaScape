/// Width of a rendered string at `scale`, excluding the trailing spacer.
pub fn text_width(text: &str, scale: f32) -> f32 {
    let count = text.chars().count() as f32;
    if count == 0.0 {
        0.0
    } else {
        (count * ADVANCE as f32 - 1.0) * scale
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_cover_uppercase_digits_and_punctuation() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:!?/-+%()'\"[]<>=*#".chars() {
            assert!(
                glyph(c).iter().any(|row| *row != 0),
                "missing glyph for {c:?}"
            );
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph(' '), [0; GLYPH_H]);
    }

    #[test]
    fn text_width_uses_one_pixel_advance_spacing() {
        assert_eq!(text_width("", 1.0), 0.0);
        assert_eq!(text_width("A", 1.0), 5.0);
        assert_eq!(text_width("AB", 1.0), 11.0);
        assert_eq!(text_width("AB", 2.0), 22.0);
    }
}
